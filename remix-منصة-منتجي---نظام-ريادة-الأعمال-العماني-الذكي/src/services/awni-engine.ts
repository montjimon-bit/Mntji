    const q = prompt.toLowerCase().trim();

    // Check previous context for multi-turn conversation
    const lastUserMsg = history
      .filter((m) => m.role === 'user')
      .slice(-2)
      .map((m) => m.text.toLowerCase())
      .join(' ');

    const combinedContext = `${lastUserMsg} ${q}`;

